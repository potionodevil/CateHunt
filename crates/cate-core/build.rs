//! Build-Skript: bettet die Commit-SHA als `CATE_COMMIT_SHA` ein.
//! Ohne Git (oder bei Fehler) -> "unknown"; bricht den Build nie.
fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-env-changed=CATE_COMMIT_SHA");
    let sha = std::env::var("CATE_COMMIT_SHA")
        .ok()
        .filter(|s| !s.trim().is_empty())
        .or_else(|| {
            std::process::Command::new("git")
                .args(["rev-parse", "HEAD"])
                .output()
                .ok()
                .filter(|o| o.status.success())
                .and_then(|o| String::from_utf8(o.stdout).ok())
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
        })
        .unwrap_or_else(|| "unknown".to_string());
    println!("cargo:rustc-env=CATE_COMMIT_SHA={sha}");
}
